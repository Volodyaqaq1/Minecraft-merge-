        'Блейз',          // 15
        'Гаст',           // 16
        'Пещерный паук',  // 17
        'Магм-куб',       // 18
        'Иссушитель',     // 19
        'Страж древности',// 20
        'Разоритель',     // 21
        'Иллюзионист',    // 22
        'Зоглин',         // 23
        'Пилагер',        // 24
